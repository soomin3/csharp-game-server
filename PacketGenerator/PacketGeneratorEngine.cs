using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using System.Text.RegularExpressions;

namespace PacketGenerator;

public static class PacketGeneratorEngine
{
    private const string Banner = "// <auto-generated by MyServer PacketGenerator>";
    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        UnmappedMemberHandling = JsonUnmappedMemberHandling.Disallow
    };
    private static readonly HashSet<string> Keywords = new(StringComparer.Ordinal)
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const", "continue",
        "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern", "false", "finally",
        "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int", "interface", "internal", "is", "lock",
        "long", "namespace", "new", "null", "object", "operator", "out", "override", "params", "private", "protected", "public",
        "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof", "stackalloc", "static", "string", "struct", "switch",
        "this", "throw", "true", "try", "typeof", "uint", "ulong", "unchecked", "unsafe", "ushort", "using", "virtual", "void",
        "volatile", "while", "record", "required", "file", "var", "dynamic", "__arglist", "__makeref", "__reftype", "__refvalue"
    };
    private static readonly HashSet<string> MemberNames = new(StringComparer.Ordinal)
    {
        "Equals", "GetHashCode", "GetType", "ToString", "MemberwiseClone", "Finalize"
    };

    public static IReadOnlyDictionary<string, string> Render(string json)
    {
        Definition definition = JsonSerializer.Deserialize<Definition>(json, JsonOptions)
            ?? throw new ArgumentException("The packet definition is empty.");
        Validate(definition);
        Packet[] packets = definition.Packets.OrderBy(packet => packet.Id)
            .ThenBy(packet => packet.Direction, StringComparer.Ordinal).ThenBy(packet => packet.Name, StringComparer.Ordinal).ToArray();
        Dictionary<string, string> result = new(StringComparer.Ordinal)
        {
            ["Common/Network/Generated/PacketId.g.cs"] = RenderIds(packets),
            ["Game/Network/Generated/IPacketHandler.g.cs"] = RenderHandler(packets),
            ["Game/Network/Generated/PacketDispatcher.g.cs"] = RenderDispatcher(packets)
        };
        foreach (Packet packet in packets)
        {
            result.Add($"Common/Network/Generated/{packet.Name}.g.cs", RenderPacket(packet));
        }
        return result;
    }

    public static IReadOnlyList<string> Generate(string definitionPath, string outputRoot)
    {
        IReadOnlyDictionary<string, string> rendered = Render(File.ReadAllText(definitionPath));
        string root = Path.GetFullPath(outputRoot);
        string prefix = Path.TrimEndingDirectorySeparator(root) + Path.DirectorySeparatorChar;
        string[] directories = { "Common/Network/Generated", "Game/Network/Generated" };
        List<string> paths = new();
        foreach ((string relativePath, string source) in rendered)
        {
            string path = Path.GetFullPath(Path.Combine(root, relativePath));
            EnsureWithinRoot(path, prefix);
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            string normalized = source.Replace("\r\n", "\n");
            if (!File.Exists(path) || File.ReadAllText(path).Replace("\r\n", "\n") != normalized)
            {
                File.WriteAllText(path, normalized, new UTF8Encoding(false));
            }
            paths.Add(path);
        }

        HashSet<string> expected = new(paths, StringComparer.OrdinalIgnoreCase);
        foreach (string relativeDirectory in directories)
        {
            string directory = Path.GetFullPath(Path.Combine(root, relativeDirectory));
            EnsureWithinRoot(directory, prefix);
            foreach (string path in Directory.EnumerateFiles(directory, "*.g.cs", SearchOption.TopDirectoryOnly))
            {
                string absolutePath = Path.GetFullPath(path);
                EnsureWithinRoot(absolutePath, prefix);
                if (!expected.Contains(absolutePath) && File.ReadAllText(absolutePath).StartsWith(Banner, StringComparison.Ordinal))
                {
                    File.Delete(absolutePath);
                }
            }
        }
        return paths;
    }

    private static void EnsureWithinRoot(string path, string rootPrefix)
    {
        if (!path.StartsWith(rootPrefix, StringComparison.OrdinalIgnoreCase))
        {
            throw new ArgumentException("Generated output must remain inside the selected solution root.");
        }
    }

    private static void Validate(Definition definition)
    {
        if (definition.Packets is null || definition.Packets.Count == 0)
        {
            throw new ArgumentException("At least one packet is required.");
        }
        HashSet<string> names = new(StringComparer.OrdinalIgnoreCase);
        HashSet<(int, string)> directions = new();
        Dictionary<int, string> idNames = new();
        Dictionary<string, int> idValues = new(StringComparer.Ordinal);
        HashSet<string> handlers = new(StringComparer.Ordinal);
        foreach (Packet packet in definition.Packets)
        {
            if (packet is null)
                throw new ArgumentException("A packet definition cannot be null.");
            RequireIdentifier(packet.Name, "packet name");
            if (!names.Add(packet.Name) || packet.Name is "PacketId" or "PacketHeader" or "PacketFramer" or "FrameResult" or "TServer" or "TSession" or "BAReader" or "BAWriter" or "IPacketHandler" or "PacketDispatcher" or "IGameSession" or "GameSession" or "ArgumentNullException" or "System")
                throw new ArgumentException($"Duplicate or reserved packet name: {packet.Name}");
            if (packet.Id <= 0 || packet.Id > ushort.MaxValue)
                throw new ArgumentException($"Packet ID must be between 1 and {ushort.MaxValue}: {packet.Name}");
            RequireIdentifier(packet.WireName, "packet ID name");
            if (packet.WireName is "None" or "PacketId" or "CompareTo" or "GetTypeCode" or "HasFlag" || MemberNames.Contains(packet.WireName))
                throw new ArgumentException($"Reserved packet ID name: {packet.WireName}");
            if (packet.Direction is not ("clientToServer" or "serverToClient"))
                throw new ArgumentException($"Invalid direction: {packet.Name}");
            if (packet.Direction == "clientToServer" && !packet.Name.EndsWith("Req", StringComparison.Ordinal))
                throw new ArgumentException($"Client request names must end with Req: {packet.Name}");
            if (packet.Direction == "serverToClient" && !packet.Name.EndsWith("Res", StringComparison.Ordinal) && !packet.Name.EndsWith("Ntf", StringComparison.Ordinal))
                throw new ArgumentException($"Server packet names must end with Res or Ntf: {packet.Name}");
            if (!directions.Add((packet.Id, packet.Direction)))
                throw new ArgumentException($"Duplicate packet ID for the same direction: {packet.Id}");
            if (idNames.TryGetValue(packet.Id, out string? priorName) && priorName != packet.WireName)
                throw new ArgumentException($"The same packet ID must use the same ID name: {packet.Id}");
            if (idValues.TryGetValue(packet.WireName, out int priorId) && priorId != packet.Id)
                throw new ArgumentException($"The same packet ID name must use the same value: {packet.WireName}");
            idNames[packet.Id] = packet.WireName;
            idValues[packet.WireName] = packet.Id;
            if (packet.Fields is null || packet.Fields.Count == 0)
                throw new ArgumentException($"At least one body field is required: {packet.Name}");
            HashSet<string> fields = new(StringComparer.Ordinal);
            foreach (Field field in packet.Fields)
            {
                if (field is null)
                    throw new ArgumentException($"A field definition cannot be null: {packet.Name}");
                RequireIdentifier(field.Name, "field name");
                if (!fields.Add(field.Name) || field.Name is "ToPacket" or "ToValue" || field.Name == packet.Name || MemberNames.Contains(field.Name))
                    throw new ArgumentException($"Duplicate or reserved field name: {packet.Name}.{field.Name}");
                if (field.Type is not ("string" or "int" or "float"))
                    throw new ArgumentException($"Unsupported field type: {packet.Name}.{field.Name} ({field.Type})");
            }
            if (packet.Direction == "clientToServer")
            {
                RequireIdentifier(packet.HandlerName, "handler name");
                if (packet.HandlerName is "IPacketHandler" or "GameHandler")
                    throw new ArgumentException($"Reserved request handler name: {packet.HandlerName}");
                if (!handlers.Add(packet.HandlerName))
                    throw new ArgumentException($"Duplicate request handler name: {packet.HandlerName}");
            }
        }
    }

    private static void RequireIdentifier(string? identifier, string description)
    {
        if (identifier is null || !Regex.IsMatch(identifier, "^[A-Za-z_][A-Za-z0-9_]*$") || Keywords.Contains(identifier))
            throw new ArgumentException($"Invalid C# {description}: {identifier}");
    }

    private static StringBuilder Start(string ns)
    {
        return new StringBuilder().AppendLine(Banner).AppendLine("#nullable enable").AppendLine()
            .AppendLine($"namespace {ns}").AppendLine("{");
    }

    private static string RenderIds(Packet[] packets)
    {
        StringBuilder code = Start("Common.Network");
        code.AppendLine("    public enum PacketId : ushort").AppendLine("    {").AppendLine("        None = 0,");
        foreach (Packet packet in packets.DistinctBy(packet => packet.Id))
            code.AppendLine($"        {packet.WireName} = {packet.Id},");
        return code.AppendLine("    }").AppendLine("}").ToString();
    }

    private static string RenderPacket(Packet packet)
    {
        StringBuilder code = Start("Common.Network");
        code.AppendLine($"    public sealed class {packet.Name}").AppendLine("    {");
        foreach (Field field in packet.Fields)
        {
            string initial = field.Type == "string" ? " = string.Empty;" : string.Empty;
            code.AppendLine($"        public {field.Type} {field.Name} {{ get; set; }}{initial}");
        }
        string size = string.Join(" + ", packet.Fields.Select(field => field.Type == "string"
            ? $"sizeof(int) + global::System.Text.Encoding.UTF8.GetByteCount(this.{field.Name})" : $"sizeof({field.Type})"));
        code.AppendLine().AppendLine("        public byte[] ToPacket()").AppendLine("        {")
            .AppendLine($"            global::Common.Network.BAWriter writer = new global::Common.Network.BAWriter(checked({size}));");
        foreach (Field field in packet.Fields)
            code.AppendLine($"            writer.Put{MethodSuffix(field.Type)}(this.{field.Name});");
        code.AppendLine($"            return writer.ToPacket(global::Common.Network.PacketId.{packet.WireName});")
            .AppendLine("        }").AppendLine()
            .AppendLine($"        public static {packet.Name}? ToValue(byte[] buffer, int offset, int length)")
            .AppendLine("        {").AppendLine("            global::Common.Network.BAReader reader = new global::Common.Network.BAReader(buffer, offset, length);")
            .AppendLine($"            {packet.Name} packet = new {packet.Name}();");
        foreach (Field field in packet.Fields)
            code.AppendLine($"            packet.{field.Name} = reader.Get{MethodSuffix(field.Type)}();");
        return code.AppendLine("            return reader.IsComplete ? packet : null;")
            .AppendLine("        }").AppendLine("    }").AppendLine("}").ToString();
    }

    private static string MethodSuffix(string type) => type switch
    {
        "int" => "Int",
        "float" => "Float",
        "string" => "String",
        _ => throw new ArgumentException($"Unsupported field type: {type}")
    };

    private static string RenderHandler(Packet[] packets)
    {
        StringBuilder code = new StringBuilder().AppendLine(Banner).AppendLine("#nullable enable")
            .AppendLine("using Common.Network;").AppendLine().AppendLine("namespace Game.Network").AppendLine("{")
            .AppendLine("    public interface IPacketHandler").AppendLine("    {");
        foreach (Packet packet in packets.Where(packet => packet.Direction == "clientToServer"))
        {
            code.AppendLine($"        void {packet.HandlerName}(IGameSession session, {packet.Name} packet)")
                .AppendLine("        {").AppendLine($"            session.Disconnect(\"Unhandled packet: {packet.Name}\");")
                .AppendLine("        }").AppendLine();
        }
        return code.AppendLine("    }").AppendLine("}").ToString();
    }

    private static string RenderDispatcher(Packet[] packets)
    {
        StringBuilder code = new StringBuilder().AppendLine(Banner).AppendLine("#nullable enable")
            .AppendLine("using Common.Network;").AppendLine().AppendLine("namespace Game.Network").AppendLine("{")
            .AppendLine("    public sealed class PacketDispatcher").AppendLine("    {")
            .AppendLine("        private readonly IPacketHandler _handler;").AppendLine()
            .AppendLine("        public PacketDispatcher(IPacketHandler handler)").AppendLine("        {")
            .AppendLine("            ArgumentNullException.ThrowIfNull(handler);").AppendLine("            _handler = handler;")
            .AppendLine("        }").AppendLine()
            .AppendLine("        public bool Dispatch(IGameSession session, PacketId id, byte[] buffer, int offset, int length)")
            .AppendLine("        {").AppendLine("            if (session.IsDisconnected)").AppendLine("            {")
            .AppendLine("                return false;").AppendLine("            }").AppendLine()
            .AppendLine("            switch (id)").AppendLine("            {");
        foreach (Packet packet in packets.Where(packet => packet.Direction == "clientToServer"))
        {
            code.AppendLine($"                case PacketId.{packet.WireName}:").AppendLine("                {")
                .AppendLine($"                    {packet.Name}? packet = {packet.Name}.ToValue(buffer, offset, length);")
                .AppendLine("                    if (packet is null)").AppendLine("                    {")
                .AppendLine($"                        session.Disconnect(\"Malformed packet: {packet.Name}\");")
                .AppendLine("                        return false;").AppendLine("                    }")
                .AppendLine($"                    _handler.{packet.HandlerName}(session, packet);")
                .AppendLine("                    return true;").AppendLine("                }");
        }
        return code.AppendLine("                default:")
            .AppendLine("                    session.Disconnect($\"Unknown packet ID: {(ushort)id}\");")
            .AppendLine("                    return false;").AppendLine("            }").AppendLine("        }")
            .AppendLine("    }").AppendLine("}").ToString();
    }

    public sealed class Definition
    {
        public List<Packet> Packets { get; set; } = new();
    }

    public sealed class Packet
    {
        public string Name { get; set; } = string.Empty;
        public int Id { get; set; }
        public string? IdName { get; set; }
        public string Direction { get; set; } = string.Empty;
        public string? Handler { get; set; }
        public List<Field> Fields { get; set; } = new();
        [JsonIgnore] public string WireName => IdName ?? Name;
        [JsonIgnore] public string HandlerName => Handler ?? "Res" + (Name.EndsWith("Req", StringComparison.Ordinal) ? Name[..^3] : Name);
    }

    public sealed class Field
    {
        public string Name { get; set; } = string.Empty;
        public string Type { get; set; } = string.Empty;
    }
}
